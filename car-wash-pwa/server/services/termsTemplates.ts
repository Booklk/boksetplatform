/** Map vendor.industry → best-fit Terms template. */
export function defaultTermsForIndustry(vendorIndustry?: string | null): TermsIndustry {
  const m: Record<string, TermsIndustry> = {
    salon: 'salon',
    barber: 'barber',
    beauty_home: 'beauty_home',
    spa: 'spa',
    home_cleaning: 'cleaning',
    cleaning: 'cleaning',
    movers: 'movers',
    car_wash: 'car_wash_fixed', // default; vendor can switch
    ac_maintenance: 'ac_maintenance',
    plumbing: 'plumbing',
    electrical: 'electrical',
    freelancer: 'freelancer',
    appliance_repair: 'appliance_repair',
    clinic: 'clinic',
    professional_services: 'professional_services',
    // 'other' has no specific template — universal handles it.
  };
  if (vendorIndustry && m[vendorIndustry]) return m[vendorIndustry];
  return 'universal';
}

/** Render a template — substitutes {vendor} and {phone} placeholders. */
export function renderTermsTemplate(
  tpl: TermsTemplate,
  vars: { vendor: string; phone?: string },
): string {
  return tpl.content
    .replaceAll('{vendor}', vars.vendor)
    .replaceAll('{phone}', vars.phone ?? '—');
}

