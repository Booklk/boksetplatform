/**
 * Look up the storefront content for an industry. Falls back to 'other'
 * if the key is unknown so a vendor on a brand-new sector still lands
 * on a complete page.
 */
export function getIndustryContent(industry: string | null | undefined): IndustryStorefrontContent {
  if (!industry) return INDUSTRY_STOREFRONT_CONTENT.other;
  return INDUSTRY_STOREFRONT_CONTENT[industry] ?? INDUSTRY_STOREFRONT_CONTENT.other;
}
