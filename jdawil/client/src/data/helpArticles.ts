export function findArticle(slug: string): HelpArticle | undefined {
  return HELP_ARTICLES.find((a) => a.slug === slug);
}

/**
 * Search articles by keyword. Tokenises the query, matches across title +
 * keywords + body. Case-insensitive, Arabic-aware.
 */
export function searchArticles(query: string): HelpArticle[] {
  const q = query.trim().toLowerCase();
  if (!q) return HELP_ARTICLES;
  const terms = q.split(/\s+/).filter(Boolean);
  return HELP_ARTICLES.filter((a) => {
    const haystack = (a.title + ' ' + a.keywords.join(' ') + ' ' + a.body).toLowerCase();
    return terms.every((t) => haystack.includes(t));
  });
}
